def build_language_file(lang_code, direction):
    """Build a single language HTML file."""
    html = original
    
    # 1. Set html lang and dir
    html = html.replace('<html lang="zh-CN">', f'<html lang="{lang_code}" dir="{direction}">')
    
    # 2. Add CSS for language links (before </style>)
    if '.lang-links{' not in html:
        html = html.replace('</style>', LANG_LINKS_CSS + '\n</style>')
    
    # 3. Replace language links div with correct active state
    current_file = f'{lang_code}.html'
    lang_links_html = make_lang_links(current_file)
    # Match the entire <div class="lang-links">...</div> block
    lang_div_pattern = r'<div class="lang-links">.*?</div>'
    html = re.sub(lang_div_pattern, lang_links_html, html, flags=re.DOTALL)
    
    # 4. Set currentLang
    html = html.replace('var currentLang = "zh-CN"', f'var currentLang = "{lang_code}"')
    
    # 5. For ar, add rtl class to body
    if direction == 'rtl':
        html = html.replace('<body>', '<body class="rtl">')
    
    # 6. Add translation patch before the LAST renderAll() call (initial call, not inside setLang)
    patch = generate_patch(lang_code)
    if patch:
        # Find the last occurrence of renderAll(); and insert patch before it
        last_idx = html.rfind('renderAll();')
        if last_idx >= 0:
            html = html[:last_idx] + patch + '\n' + html[last_idx:]
    
    # 7. Write file
    filename = f'{lang_code}.html'
    with open(filename, 'w', encoding='utf-8') as f:
        f.write(html)
    
    size = os.path.getsize(filename)
    print(f"  Generated {filename} ({size:,} bytes)")
    return filename


